/**
 * Regenerates `apps/humanity-app/src/shared/styles/themes.css` from the host's own
 * palettes: the generated Swift themes in `paritytech/polkadot-app-design-system-ios`
 * (`Sources/DesignSystem/Generated/colors/themes/*Theme.swift`), the same table
 * the iOS app resolves `Theme.subscribe` names against.
 *
 *   node scripts/sync-theme-palettes.mjs <path-to-polkadot-app-design-system-ios>
 *
 * Every semantic token becomes `--ds-<kebab-name>` under
 * `:root[data-theme="<theme id>"]`. The host's default theme (Berlin Night)
 * also owns bare `:root`, so the app renders it before the host answers.
 * `color-scheme` follows the rule the hosts use to pick a theme's wire variant:
 * Rec. 601 luma of `bgSurfaceMain` above one half is Light.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DEFAULT_THEME = "berlinNight";
const OUT = new URL("../src/shared/styles/themes.css", import.meta.url);

const root = process.argv[2];
if (root == null) {
  console.error("usage: node scripts/sync-theme-palettes.mjs <polkadot-app-design-system-ios checkout>");
  process.exit(1);
}

const themesDir = join(root, "Sources/DesignSystem/Generated/colors/themes");
const commit = execFileSync("git", ["-C", root, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function parseTheme(source, file) {
  const id = /id:\s*"([^"]+)"/.exec(source)?.[1];
  if (id == null) throw new Error(`${file}: no theme id`);
  const tokens = [];
  for (const [, name, kind, raw] of source.matchAll(/let (\w+) = UIColor\((rgbHex|rgbaHex): 0x([0-9A-Fa-f_]+)\)/g)) {
    const hex = raw.replaceAll("_", "").toLowerCase();
    if (hex.length !== (kind === "rgbHex" ? 6 : 8)) throw new Error(`${file}: bad ${name} 0x${raw}`);
    tokens.push([name, `#${hex}`]);
  }
  if (tokens.length === 0) throw new Error(`${file}: no colors`);
  return { id, tokens };
}

function isLight(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  return 0.299 * r + 0.587 * g + 0.114 * b > 0.5;
}

const themes = readdirSync(themesDir)
  .filter((f) => f.endsWith("Theme.swift"))
  .sort()
  .map((f) => parseTheme(readFileSync(join(themesDir, f), "utf8"), f));

const names = themes[0].tokens.map(([n]) => n).join();
for (const t of themes) {
  if (t.tokens.map(([n]) => n).join() !== names) throw new Error(`${t.id}: token set differs from ${themes[0].id}`);
}
if (!themes.some((t) => t.id === DEFAULT_THEME)) throw new Error(`default theme ${DEFAULT_THEME} missing`);

const blocks = themes.map(({ id, tokens }) => {
  const surface = tokens.find(([n]) => n === "bgSurfaceMain")[1];
  const selector = id === DEFAULT_THEME ? `:root,\n:root[data-theme="${id}"]` : `:root[data-theme="${id}"]`;
  const body = tokens.map(([n, v]) => `  --ds-${kebab(n)}: ${v};`).join("\n");
  return `${selector} {\n  color-scheme: ${isLight(surface) ? "light" : "dark"};\n${body}\n}`;
});

writeFileSync(
  OUT,
  `/* GENERATED by scripts/sync-theme-palettes.mjs from
   paritytech/polkadot-app-design-system-ios@${commit}. Do not edit by hand.
   Host theme ids: ${themes.map((t) => t.id).join(", ")}. */

${blocks.join("\n\n")}
`,
);
console.log(`wrote ${themes.length} themes (${themes[0].tokens.length} tokens each) from @${commit}`);
