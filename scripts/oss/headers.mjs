// Licence headers on every source file.
//
//   node scripts/oss/headers.mjs --check   list files without a header; exit 1 if any (CI)
//   node scripts/oss/headers.mjs --fix     add the header where it is missing
//
// The licence comes from the root package.json's "license" field, so changing
// the licence is one edit there plus `--fix --replace`. A file that carries a
// non-GPL SPDX-License-Identifier is left alone: it is vendored or licensed
// differently on purpose (`--verbose` lists them; see THIRD_PARTY_NOTICES.md).
//
// Node built-ins only, so it runs before `npm ci`.
import { execFileSync } from "node:child_process"
import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { extname, join, relative } from "node:path"

const args = process.argv.slice(2)
const flag = (name) => args.includes(name)
const rootArg = args.indexOf("--root")
const ROOT = rootArg >= 0 ? args[rootArg + 1] : process.cwd()
const MODE = flag("--fix") ? "fix" : "check"
const REPLACE = flag("--replace")

const HOLDER = "Parity Technologies (UK) Ltd."
const YEAR = 2026
const SPDX = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).license
if (!SPDX) throw new Error("root package.json has no license field")

/** comment style per extension: [line prefix] or [open, prefix, close] */
const STYLES = {
  ".ts": "//", ".tsx": "//", ".mts": "//", ".cts": "//",
  ".js": "//", ".jsx": "//", ".mjs": "//", ".cjs": "//",
  ".css": "/*",
  ".sh": "#", ".py": "#", ".yml": "#", ".yaml": "#", ".feature": "#",
  ".html": "<!--",
}

/** never headed: generated, vendored or build output */
const SKIP_DIRS = new Set(["node_modules", ".git", ".next", "out", "dist", "coverage", ".papi", ".turbo", "playwright-report", "test-results"])
const SKIP_FILES = [/\.d\.ts$/, /(^|\/)next-env\.d\.ts$/, /\.min\.(js|css)$/]
/** a generated file says so near its top; regenerating would drop a header anyway */
const GENERATED = /@generated|DO NOT EDIT|auto-generated|autogenerated/i

function listFiles() {
  try {
    const out = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] })
    return out.split("\0").filter(Boolean)
  } catch {
    const files = []
    const walk = (dir) => {
      for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
        const rel = dir ? `${dir}/${entry.name}` : entry.name
        if (entry.isDirectory()) { if (!SKIP_DIRS.has(entry.name)) walk(rel) }
        else files.push(rel)
      }
    }
    walk("")
    return files
  }
}

function headerLines(style) {
  const lines = [`Copyright ${YEAR} ${HOLDER}`, `SPDX-License-Identifier: ${SPDX}`]
  if (style === "/*") return ["/*", ...lines.map((l) => ` * ${l}`), " */"]
  if (style === "<!--") return ["<!--", ...lines.map((l) => `  ${l}`), "-->"]
  return lines.map((l) => `${style} ${l}`)
}

const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
const OURS = new RegExp(`Copyright \\d{4}(-\\d{4})? ${escape(HOLDER)}(?![\\w.])`)
/** an earlier wording of our own line (e.g. without "(UK) Ltd."): rewritten in place, never stacked */
const OURS_OLD = /Copyright (\d{4}(?:-\d{4})?) Parity Technologies(?! \(UK\) Ltd\.)\b\.?/
const ANY_SPDX = /SPDX-License-Identifier:\s*(\S+)/

/** the lines a header may not go above: a shebang, an XML/doctype prolog */
function prologLength(lines, ext) {
  if (lines[0]?.startsWith("#!")) return 1
  if (ext === ".html" && /^<!doctype/i.test(lines[0] ?? "")) return 1
  return 0
}

const missing = []
const foreign = []
let fixed = 0
for (const rel of listFiles()) {
  const ext = extname(rel)
  const style = STYLES[ext]
  if (!style) continue
  if (rel.split("/").some((part) => SKIP_DIRS.has(part))) continue
  if (SKIP_FILES.some((re) => re.test(rel))) continue
  const path = join(ROOT, rel)
  const text = readFileSync(path, "utf8")
  const head = text.split("\n", 12).join("\n")
  if (GENERATED.test(head)) continue
  const spdx = head.match(ANY_SPDX)
  if (OURS.test(head) && spdx?.[1] === SPDX) continue
  // another licence on purpose (vendored Apache-2.0 code, say): leave it, list it with --verbose
  if (spdx && !spdx[1].startsWith("GPL-3.0")) { foreign.push(`${rel} (${spdx[1]})`); continue }
  // our GPL under an older variant: only --replace rewrites it
  if (spdx && spdx[1] !== SPDX && !REPLACE) { missing.push(`${rel} (says ${spdx[1]}; run --fix --replace)`); continue }

  if (MODE === "check") { missing.push(rel); continue }
  let lines = text.split("\n")
  if (spdx) {
    lines = lines.map((l) => l.replace(ANY_SPDX, `SPDX-License-Identifier: ${SPDX}`))
    // an older wording of our copyright line: bring it up to date in place
    const olderAt = OURS.test(head) ? -1 : lines.slice(0, 12).findIndex((l) => OURS_OLD.test(l))
    if (olderAt >= 0) lines[olderAt] = lines[olderAt].replace(OURS_OLD, `Copyright $1 ${HOLDER}`)
    // an SPDX line with no copyright line above it: add ours, in the same comment style
    else if (!OURS.test(head)) {
      const at = lines.findIndex((l) => ANY_SPDX.test(l))
      lines.splice(at, 0, `${lines[at].slice(0, lines[at].indexOf("SPDX-License-Identifier"))}Copyright ${YEAR} ${HOLDER}`)
    }
  } else {
    const at = prologLength(lines, ext)
    const blank = lines[at] === "" ? [] : [""]
    lines = [...lines.slice(0, at), ...headerLines(style), ...blank, ...lines.slice(at)]
  }
  writeFileSync(path, lines.join("\n"))
  fixed++
}

const where = relative(process.cwd(), ROOT) || "."
if (MODE === "fix") console.log(`headers: added or updated ${fixed} in ${where}`)
if (foreign.length && flag("--verbose")) console.log(`kept their own licence (${foreign.length}):\n  ${foreign.join("\n  ")}`)
if (missing.length) {
  console.error(`headers: ${missing.length} file(s) without the ${SPDX} header:\n  ${missing.slice(0, 50).join("\n  ")}${missing.length > 50 ? `\n  … and ${missing.length - 50} more` : ""}`)
  console.error("run: node scripts/oss/headers.mjs --fix")
  process.exit(1)
}
if (MODE === "check") console.log(`headers: ok (${SPDX})`)
