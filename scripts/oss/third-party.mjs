// THIRD_PARTY_NOTICES.md: the licences of everything the apps ship that is not
// ours, generated from package-lock.json and the installed node_modules.
//
//   node scripts/oss/third-party.mjs           regenerate THIRD_PARTY_NOTICES.md (after npm ci)
//   node scripts/oss/third-party.mjs --check   fail if a dependency has a licence outside
//                                              ALLOWED, or if the file is stale
//
// Shipped = every lockfile package that is not dev-only. Build tools and test
// libraries are not distributed with the apps, so they are not listed (their
// licences are still checked against ALLOWED). Assets that do not come from npm
// (fonts, icons, copied code) are listed in scripts/oss/notices-extra.md.
//
// The output is the same on every machine. Packages limited to one platform by
// `os` or `cpu` in the lockfile (the native builds of esbuild, SWC, Rollup and the
// like) are installed only on that platform, so they are checked from the lockfile
// and not listed; the package each belongs to is. Versions are left out, so a bump
// that keeps a package's licence text leaves the file as it is.
// Node built-ins only.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const ROOT = process.cwd()
const CHECK = process.argv.includes("--check")
const OUT = join(ROOT, "THIRD_PARTY_NOTICES.md")

/** licences the repository may ship or build with */
const ALLOWED = new Set([
  "MIT", "MIT-0", "ISC", "0BSD", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "BlueOak-1.0.0", "Zlib",
  "Unlicense", "CC0-1.0", "CC-BY-3.0", "CC-BY-4.0", "Python-2.0", "Unicode-3.0", "W3C-20150513",
  // copyleft that GPL-3.0-or-later can carry
  "GPL-3.0-or-later WITH Classpath-exception-2.0", "GPL-3.0-only WITH Classpath-exception-2.0", "LGPL-3.0-or-later", "MPL-2.0",
])
/** packages whose licence is not an SPDX id above, each with the reason it is accepted */
const EXCEPTIONS = {
  sentry: "The Sentry CLI (FSL-1.1-Apache-2.0), a build-time tool that uploads source maps only when a deployer configures their own Sentry project; it is not shipped.",
}

const lock = JSON.parse(readFileSync(join(ROOT, "package-lock.json"), "utf8"))
const normalise = (l) => (typeof l === "string" ? l : Array.isArray(l) ? l.map((x) => x.type ?? x).join(" OR ") : l?.type ?? "UNKNOWN")
const okLicence = (expr) => expr.replace(/[()]/g, "").split(/\s+OR\s+/).some((part) => ALLOWED.has(part.trim())) ||
  expr.replace(/[()]/g, "").split(/\s+AND\s+/).every((part) => ALLOWED.has(part.trim()))

const LICENCE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i
const shipped = new Map() // name@version -> { name, version, licence, text }
const problems = []
for (const [path, entry] of Object.entries(lock.packages ?? {})) {
  if (!path.includes("node_modules/") || entry.link) continue
  const name = entry.name ?? path.slice(path.lastIndexOf("node_modules/") + 13)
  const pkgJson = join(ROOT, path, "package.json")
  const meta = existsSync(pkgJson) ? JSON.parse(readFileSync(pkgJson, "utf8")) : {}
  const licence = normalise(entry.license ?? meta.license ?? meta.licenses)
  if (!okLicence(licence) && !EXCEPTIONS[name]) problems.push(`${name}@${entry.version}: ${licence}${entry.dev ? " (dev)" : ""}`)
  if (entry.dev || entry.devOptional || entry.os || entry.cpu) continue
  if (!existsSync(join(ROOT, path))) problems.push(`${name}@${entry.version}: not installed; run npm ci first`)
  const file = existsSync(join(ROOT, path)) ? readdirSync(join(ROOT, path)).find((f) => LICENCE_FILE.test(f)) : undefined
  const text = file ? readFileSync(join(ROOT, path, file), "utf8").replace(/\r\n/g, "\n").trim() : ""
  const key = `${name}\0${text}`
  if (!shipped.has(key)) shipped.set(key, { name, licence, text })
}

// one block per distinct licence text, listing every package that ships it
const byText = new Map()
for (const pkg of [...shipped.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const k = pkg.text || `(no licence file; declared ${pkg.licence})`
  if (!byText.has(k)) byText.set(k, [])
  byText.get(k).push(pkg)
}
const counts = new Map() // packages per licence, each name once
for (const [licence, names] of Object.entries(Object.groupBy([...shipped.values()], (p) => p.licence)))
  counts.set(licence, new Set(names.map((p) => p.name)).size)
const extraPath = join(ROOT, "scripts/oss/notices-extra.md")
const extra = existsSync(extraPath) ? readFileSync(extraPath, "utf8").trim() : ""

const body = [
  "# Third-party notices",
  "",
  "Generated by `node scripts/oss/third-party.mjs` from `package-lock.json`; do not edit by hand.",
  "Platform-specific native builds of listed packages (for example `@esbuild/linux-x64`) are covered",
  "by the entry of the package they belong to.",
  "The apps in this repository are licensed under GPL-3.0-or-later (see LICENSE). They ship the",
  "components below, each under its own licence.",
  "",
  "## Summary",
  "",
  "| Licence | Packages |",
  "| :-- | --: |",
  ...[...counts].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`),
  "",
  ...(Object.keys(EXCEPTIONS).length ? ["## Licences outside the usual allow-list", "", ...Object.entries(EXCEPTIONS).map(([n, why]) => `- \`${n}\`: ${why}`), ""] : []),
  ...(extra ? [extra, ""] : []),
  "## npm packages",
  "",
  ...[...byText].flatMap(([text, pkgs]) => [
    `### ${pkgs.map((p) => p.name).join(", ")}`,
    "",
    `License: ${[...new Set(pkgs.map((p) => p.licence))].join(", ")}`,
    "",
    "```text",
    text.replace(/```/g, "'''"),
    "```",
    "",
  ]),
].join("\n")

if (problems.length) {
  console.error(`third-party: ${problems.length} package(s) with a licence outside the allow-list:\n  ${problems.join("\n  ")}`)
  if (CHECK) process.exit(1)
}
if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : ""
  if (current !== body) {
    console.error("third-party: THIRD_PARTY_NOTICES.md is stale (a shipped package was added or removed, or its licence")
    console.error("text changed). Run `npm ci && node scripts/oss/third-party.mjs` and commit the result.")
    process.exit(1)
  }
  console.log(`third-party: ok (${new Set([...shipped.values()].map((p) => p.name)).size} shipped packages)`)
} else {
  writeFileSync(OUT, body)
  console.log(`third-party: wrote THIRD_PARTY_NOTICES.md (${new Set([...shipped.values()].map((p) => p.name)).size} shipped packages, ${byText.size} licence texts)`)
}
